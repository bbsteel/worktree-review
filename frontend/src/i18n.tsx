function isLocale(value: string | null): value is Locale {
  return value === 'en' || value === 'zh-CN'
}

function detectLocale(): Locale {
  if (typeof window !== 'undefined') {
    try {
      const storedLocale = window.localStorage.getItem(LOCALE_STORAGE_KEY)
      if (isLocale(storedLocale)) {
        return storedLocale
      }
    } catch {
      // Storage can be unavailable in privacy-restricted browser contexts.
    }
  }

  if (typeof navigator !== 'undefined' && /^zh(?:-|$)/i.test(navigator.language)) {
    return 'zh-CN'
  }
  return 'en'
}

export function translate(locale: Locale, key: string, variables?: TranslationVariables): string {
  const hasLocaleTranslation = Object.prototype.hasOwnProperty.call(messages[locale], key)
  const template = messages[locale][key] ?? messages.en[key] ?? key
  if (!variables) {
    return hasLocaleTranslation || locale === 'en' ? template : localizeFallbackValue(template)
  }
  const interpolated = template.replace(/\{(\w+)\}/g, (placeholder, variableName: string) => {
    const value = variables[variableName]
    return value === undefined ? placeholder : String(value)
  })
  return hasLocaleTranslation || locale === 'en' ? interpolated : localizeFallbackValue(interpolated)
}

function localizeFallbackValue(value: string): string {
  const minutesAndSeconds = value.match(/^(\d+)m (\d+)s$/)
  if (minutesAndSeconds) {
    return `${minutesAndSeconds[1]} 分 ${minutesAndSeconds[2]} 秒`
  }
  const seconds = value.match(/^(\d+)s$/)
  if (seconds) {
    return `${seconds[1]} 秒`
  }
  return value
}

interface I18nContextValue {
  locale: Locale
  setLocale: (nextLocale: Locale) => void
  t: (key: string, variables?: TranslationVariables) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)
const FALLBACK_I18N_CONTEXT: I18nContextValue = {
  locale: 'en',
  setLocale: () => undefined,
  t: (key, variables) => translate('en', key, variables),
}

export function I18nProvider({ children, initialLocale }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocale] = useState<Locale>(() => initialLocale ?? detectLocale())

  useEffect(() => {
    document.documentElement.lang = locale
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, locale)
    } catch {
      // Storage can be unavailable in privacy-restricted browser contexts.
    }
  }, [locale])

  const contextValue = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key, variables) => translate(locale, key, variables),
    }),
    [locale],
  )

  return <I18nContext.Provider value={contextValue}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext) ?? FALLBACK_I18N_CONTEXT
}
